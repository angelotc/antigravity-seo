	pdf.SetXY(22, 59)
	pdf.CellFormat(28, 7, fmt.Sprintf("%d", data.Scores.Overall), "", 0, "C", false, 0, "")

	pdf.SetFont(fontFamily, "", 7)
	pdf.SetTextColor(colorWhite[0], colorWhite[1], colorWhite[2])
	pdf.SetXY(22, 67)
	pdf.CellFormat(28, 4, "OUT OF 100", "", 0, "C", false, 0, "")

	// Status & Executive Narrative (middle and right)
	pdf.SetFont(fontFamily, "B", 11)
	pdf.SetTextColor(colorDarkNavy[0], colorDarkNavy[1], colorDarkNavy[2])
