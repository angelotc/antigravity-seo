// PDFReviewResult represents post-generation quality review
type PDFReviewResult struct {
	Status    string `json:"status"` // "PASS" or "WARN"
	PageCount int    `json:"page_count"`
	SizeBytes int64  `json:"size_bytes"`
	Message   string `json:"message"`
}

// RenderNativePDF creates an enterprise A4 PDF report in pure Go, matching claude-seo styling.
func RenderNativePDF(data *AuditData, outputPath string) (*PDFReviewResult, error) {
	pdfBytes, err := RenderNativePDFBytes(data)
	if err != nil {
		return nil, err
	}

	if err := os.WriteFile(outputPath, pdfBytes, 0o644); err != nil {
		return nil, fmt.Errorf("saving PDF to %s: %w", outputPath, err)
	}

	fi, err := os.Stat(outputPath)
	var sizeBytes int64
	if err == nil {
		sizeBytes = fi.Size()
	}

	// Post-generation review
	review := &PDFReviewResult{
		Status:    "PASS",
		SizeBytes: sizeBytes,
		Message:   "PDF generated successfully with pure Go engine",
	}
	if sizeBytes < 1024 {
		review.Status = "WARN"
		review.Message = "Generated PDF file size is unexpectedly small"
	}

	return review, nil
}

// RenderNativePDFBytes compiles the AuditData into a standalone A4 PDF byte buffer
func RenderNativePDFBytes(data *AuditData) ([]byte, error) {
	// A4 portrait: 210 x 297 mm
	// Margins: Left=18mm, Top=22mm, Right=18mm, Bottom=25mm
	// Printable width = 210 - (18 * 2) = 174mm
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(18, 22, 18)
	pdf.SetAutoPageBreak(true, 25)
	pdf.AliasNbPages("{nb}")

	// Register the embedded Latin+Japanese font before any SetFont/AddPage call.
	pdf.AddUTF8FontFromBytes(fontFamily, "", fontRegularBytes)
	pdf.AddUTF8FontFromBytes(fontFamily, "B", fontBoldBytes)

	// Running header and footer
	pdf.SetHeaderFunc(func() {
		if pdf.PageNo() > 1 {
			pdf.SetFont(fontFamily, "B", 8)
			pdf.SetTextColor(colorNavy[0], colorNavy[1], colorNavy[2])
			pdf.SetXY(18, 12)
			pdf.Cell(80, 5, "ANTIGRAVITY SEO & GEO AUDIT REPORT")

			pdf.SetFont(fontFamily, "", 8)
			pdf.SetTextColor(colorMuted[0], colorMuted[1], colorMuted[2])
			pdf.SetXY(98, 12)
			pdf.CellFormat(94, 5, data.Host, "", 0, "R", false, 0, "")

			pdf.SetDrawColor(colorGrid[0], colorGrid[1], colorGrid[2])
			pdf.SetLineWidth(0.3)
			pdf.Line(18, 18, 192, 18)
		}
	})

	pdf.SetFooterFunc(func() {
		pdf.SetDrawColor(colorGrid[0], colorGrid[1], colorGrid[2])
		pdf.SetLineWidth(0.3)
		pdf.Line(18, 282, 192, 282)

		pdf.SetFont(fontFamily, "", 8)
		pdf.SetTextColor(colorMuted[0], colorMuted[1], colorMuted[2])
		pdf.SetXY(18, 284)
		pdf.Cell(60, 5, "Confidential — Generated by Antigravity SEO")

		pdf.SetXY(78, 284)
		pdf.CellFormat(54, 5, fmt.Sprintf("Page %d of {nb}", pdf.PageNo()), "", 0, "C", false, 0, "")

		pdf.SetXY(132, 284)
		pdf.CellFormat(60, 5, data.Host, "", 0, "R", false, 0, "")
	})

	pdf.AddPage()

	// ── 1. Header Banner (Navy with Gold Accent) ──
	drawHeaderBanner(pdf, data)

	// ── 2. Executive Scorecard & Health Summary ──
	drawExecutiveScorecard(pdf, data)

	// ── 3. Category Score Cards (4 columns) ──
	drawCategoryCards(pdf, data)

	// ── 4. Priority Action Items & Findings ──
	drawFindingsSection(pdf, data)

	// ── 5. Technical & Server Diagnostics ──
	drawTechnicalDiagnostics(pdf, data)

	// ── 6. Content, Schema & International Analysis ──
	drawContentAndSchemaDiagnostics(pdf, data)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("rendering PDF document: %w", err)
	}

	return buf.Bytes(), nil
}

