// fontFamily is the embedded UTF-8 font used throughout the PDF report. It
// covers Latin and Japanese glyphs (M PLUS 1p, SIL OFL 1.1 licensed — see
// fonts/OFL.txt) so titles, descriptions, and issue text render correctly
// instead of the mojibake produced by fpdf's core "Arial" (Latin-1) font.
const fontFamily = "mplus1p"

//go:embed fonts/MPLUS1p-Regular.ttf
var fontRegularBytes []byte

//go:embed fonts/MPLUS1p-Bold.ttf
var fontBoldBytes []byte

// Brand color palette matching claude-seo enterprise A4 reports
